import pandas as pd
import numpy as np
from openpyxl import load_workbook

# ------------------------------------------------------------
# 1. ЗАГРУЗКА ДАННЫХ ИЗ ИСХОДНОГО ФАЙЛА
# ------------------------------------------------------------
input_file = 'opros_VPS.xlsx'
df = pd.read_excel(input_file, sheet_name='Опросник_ВПС')

# ------------------------------------------------------------
# 2. УДАЛЕНИЕ НЕНУЖНЫХ КОЛОНОК
# ------------------------------------------------------------
columns_to_drop = ['ФИО_матери', 'место_проживания', 'возраст_выявления_ВПС_мес', 'тип_ВПС']
df = df.drop(columns=[col for col in columns_to_drop if col in df.columns])

# ------------------------------------------------------------
# 3. ПРЕОБРАЗОВАНИЯ (в соответствии с таблицей)
# ------------------------------------------------------------

# ---- Курение (0 – Нет, 1 – до 5, 2 – 5-10, 3 – более пачки) ----
smoking_map = {
    'Нет': 0,
    'Да (до 5 сигарет/день)': 5,
    'Да (5-10 сигарет/день)': 10,
    'Да (более 1 пачки/день)': 20
}
df['курение'] = df['курение'].map(smoking_map).fillna(0).astype(int)

# ---- Диабет матери (0 – нет, 1 – гестационный, 2 – прегестационный) ----
diabetes_map = {
    'Нет': 0,
    'Гестационный': 1,
    'Прегестационный (1 тип)': 2,
    'Прегестационный (2 тип)': 2.5,
}
df['диабет_матери'] = df['диабет_матери'].map(diabetes_map).fillna(0).astype(int)

# ---- Фолиевая кислота (0 – нет, 1 – 400 мкг, 2 – 800+ мкг) ----
folic_map = {
    'Нет': 0,
    'Да (400 мкг/сут)': 1,
    'Да (800 мкг/сут и более)': 2
}
df['фолиевая_кислота'] = df['фолиевая_кислота'].map(folic_map).fillna(0).astype(int)

# ---- Гипертензия матери (0 – нет, 1 – да) ----
df['гипертензия_матери'] = df['гипертензия_матери'].map({'Нет': 0, 'Да': 1}).fillna(0).astype(int)

# ---- TORCH-инфекция (0 – нет, 1 – да) ----
df['TORCH_инфекция'] = df['TORCH_инфекция'].map({'Нет': 0, 'Да': 1}).fillna(0).astype(int)

# ---- Отягощенный акушерский анамнез (группировка по тяжести) ----
def map_obstetric(value):
    if pd.isna(value):
        return 0
    s = str(value)
    if 'Нет осложнений' in s or 'первая беременность' in s:
        return 0
    if 'Самопроизвольные выкидыши' in s or 'Медицинские аборты' in s:
        return 1
    if 'Мертворождение' in s or 'Неонатальная смерть' in s:
        return 2
    if 'Преждевременные роды' in s or 'ЗВУР' in s or 'макросомией' in s:
        return 3
    return 0

df['отягощенный_акушерский_анамнез'] = df['отягощенный_акушерский_анамнез'].apply(map_obstetric).astype(int)

# ---- Пол ребёнка (0 – Ж, 1 – М) ----
df['пол_ребёнка'] = df['пол_ребёнка'].map({'Ж': 0.5, 'М': 1.5}).fillna(0).astype(int)

# ---- Тип поселения (0 – город, 1 – село) ----
df['тип_поселения'] = df['тип_поселения'].map({'город': 0.5, 'село': 1.5}).fillna(0).astype(int)

# ---- ВПС у плода (целевая переменная: 0 – нет, 1 – да) ----
df['ВПС_у_плода'] = df['ВПС_у_плода'].map({'Нет': 0, 'Да': 1}).fillna(0).astype(int)

# ------------------------------------------------------------
# 4. ПРОВЕРКА ЧИСЛОВЫХ ПОЛЕЙ
# ------------------------------------------------------------
numeric_cols = ['возраст_матери', 'возраст_отца', 'ИМТ_матери',
                'ВПС_у_родственников_баллы_0_6', 'гипертония_у_родственников_баллы_0_6',
                'гемоглобин_г_л']
for col in numeric_cols:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors='coerce')

# ------------------------------------------------------------
# 5. СОХРАНЕНИЕ В ТОТ ЖЕ ФАЙЛ НА ПЕРВЫЙ СВОБОДНЫЙ ЛИСТ
# ------------------------------------------------------------
# Загружаем книгу, чтобы узнать существующие листы
book = load_workbook(input_file)
existing_sheets = book.sheetnames

# Находим первый свободный номер листа
sheet_num = 1
while f'Sheet{sheet_num}' in existing_sheets:
    sheet_num += 1
new_sheet_name = f'Sheet{sheet_num}'

# Сохраняем с новым листом (не удаляя старые)
with pd.ExcelWriter(input_file, engine='openpyxl', mode='a', if_sheet_exists='replace') as writer:
    df.to_excel(writer, sheet_name=new_sheet_name, index=False)

print(f"✅ Данные добавлены в файл '{input_file}' на новый лист '{new_sheet_name}'")
print(f"📊 Существующие листы: {existing_sheets}")
print(f"➕ Добавлен лист: {new_sheet_name}")

# ------------------------------------------------------------
# 6. ВЫВОД СТАТИСТИКИ
# ------------------------------------------------------------
print("\n" + "="*60)
print("СТАТИСТИКА ОБРАБОТАННЫХ ДАННЫХ")
print("="*60)

print("\n📋 Распределение ключевых признаков:")
print("\nКурение (0=нет, 1=до5, 2=5-10, 3=>пачки):")
print(df['курение'].value_counts().sort_index())

print("\nДиабет матери (0=нет, 1=гестац, 2=прегестац):")
print(df['диабет_матери'].value_counts().sort_index())

print("\nФолиевая кислота (0=нет, 1=400, 2=800+):")
print(df['фолиевая_кислота'].value_counts().sort_index())

print("\nОтягощенный акушерский анамнез (0-3):")
print(df['отягощенный_акушерский_анамнез'].value_counts().sort_index())

print("\nПол ребёнка (0=Ж, 1=М):")
print(df['пол_ребёнка'].value_counts().sort_index())

print("\nТип поселения (0=город, 1=село):")
print(df['тип_поселения'].value_counts().sort_index())


print("\n🔍 Первые 5 строк обработанных данных:")
print(df.head().to_string())

print("\n" + "="*60)
print("СПИСОК КОЛОНОК:")
print("="*60)
for i, col in enumerate(df.columns, 1):
    print(f"{i:2}. {col:35} : {df[col].dtype}")